import uuid


class Gрядка:
    def __init__(self, название, площадь, культура, сезон):
        self.id = uuid.uuid4()
        self.название = название
        self.площадь = площадь
        self.культура = культура
        self.сезон = сезон

    def __repr__(self):
        return f"Gрядка(id={self.id}, название={self.название}, площадь={self.площадь}, культура={self.культура}, сезон={self.сезон})"


class ХранилищеГрядок:
    def __init__(self):
        self._грядки = {}
        self._последовательный = 0

    def добавить(self, название, площадь, культура, сезон):
        грядка = Gрядка(название, площадь, культура, сезон)
        self._грядки[gрядка.id] = грядка
        self._последовательный += 1
        return грядка

    def получить(self, идентификатор):
        return self._грядки.get(идентификатор)

    def список(self):
        return list(self._грядки.values())

    def __len__(self):
        return len(self._грядки)


if __name__ == "__main__":
    хранилище = ХранилищеГрядок()
    грядка1 = хранилище.добавить("Рассада", 0.5, "Томат", "Весна")
    грядка2 = хранилище.добавить("Зелень", 0.3, "Укроп", "Лето")
    грядка3 = хранилище.добавить("Корни", 0.4, "Морковь", "Осень")
    print("Добавлено грядок:", len(хранилище))
    print("Грядка1:", грядка1)
    print("Получить по id:", хранилище.получить(грядка1.id))
    print("Список:", хранилище.список())
    print("Получить несуществующую:", хранилище.получить(uuid.uuid4()))
