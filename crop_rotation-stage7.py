import collections


class Gрядка:
    def __init__(self, название, площадь, культура, сезон):
        self.название = название
        self.площадь = площадь
        self.культура = культура
        self.сезон = сезон


class Посадка:
    def __init__(self, грядка, культура, урожай=None):
        self.грядка = грядка
        self.культура = культура
        self.урожай = урожай


def собрать_посадки_для_грядки(грядка, посадки):
    """Возвращает список посадок, принадлежащих грядке."""
    return [посадка for посадка in посадки if посадка.грядка is грядка]


def собрать_посадки_для_грядки_по_названию(грядка, посадки):
    """Возвращает список посадок для грядки с указанным названием."""
    return собрать_посадки_для_грядки(грядка, посадки)


def проверить_целостность_связи(грядка, посадки):
    """
    Проверяет, что у грядки есть хотя бы одна посадка.
    Возвращает True, если связь целостна, иначе False.
    """
    return len(собрать_посадки_для_грядки(грядка, посадки)) > 0


def собрать_посадки_для_грядки_с_проверкой(грядка, посадки):
    """
    Возвращает список посадок для грядки.
    Если связь нарушена (нет посадок), возвращает пустой список.
    """
    посадки_грядки = собрать_посадки_для_грядки(грядка, посадки)
    return посадки_грядки


def собрать_статистику_посадок(грядка, посадки):
    """
    Возвращает словарь со статистикой посадок для грядки:
    - количество посадок
    - уникальные культуры
    - есть ли урожай
    """
    посадки_грядки = собрать_посадки_для_грядки(грядка, посадки)
    культуры = [посадка.культура for посадка in посадки_грядки]
    return {
        "количество": len(посадки_грядки),
        "культуры": list(collections.OrderedDict.fromkeys(культуры).keys()),
        "есть_урожай": any(посадка.урожай is not None for посадка in посадки_грядки),
    }


def найти_грядку_по_названию(грядка, название):
    """Возвращает грядку с указанным названием или None."""
    for candidate in грядка:
        if candidate.название == название:
            return candidate
    return None


def собрать_посадки_для_сезона(грядка, сезон, посадки):
    """
    Возвращает список посадок для грядки в указанном сезоне.
    Проверяет целостность связи.
    """
    посадки_грядки = собрать_посадки_для_грядки(грядка, посадки)
    return [
        посадка
        for посадка in посадки_грядки
        if hasattr(посадка, "сезон") and посадка.сезон == сезон
    ]


def проверить_целостность_всех_грядок(грядки, посадки):
    """
    Проверяет целостность связи для всех грядок.
    Возвращает список названий грядок без посадок.
    """
    нарушенные = []
    for грядка in грядки:
        if not проверить_целостность_связи(грядка, посадки):
            нарушенные.append(грядка.название)
    return нарушенные
